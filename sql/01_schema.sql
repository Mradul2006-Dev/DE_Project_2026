BEGIN;

CREATE SCHEMA dream11;
SET LOCAL search_path TO dream11;

CREATE TABLE teams (
    team_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name text NOT NULL UNIQUE,
    short_name text NOT NULL UNIQUE CHECK (short_name ~ '^[A-Z]{2,5}$'),
    team_type text NOT NULL CHECK (team_type IN ('FRANCHISE', 'INTERNATIONAL'))
);

CREATE TABLE players (
    player_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL,
    team_id bigint NOT NULL REFERENCES teams (team_id) ON DELETE RESTRICT,
    role text NOT NULL CHECK (role IN ('WK', 'BAT', 'AR', 'BOWL')),
    credits numeric(5, 1) NOT NULL CHECK (credits > 0 AND credits <= 100),
    is_active boolean NOT NULL
);

CREATE TABLE matches (
    match_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament text NOT NULL,
    home_team_id bigint NOT NULL REFERENCES teams (team_id) ON DELETE RESTRICT,
    away_team_id bigint NOT NULL REFERENCES teams (team_id) ON DELETE RESTRICT,
    venue text NOT NULL,
    starts_at timestamptz NOT NULL,
    status text NOT NULL CHECK (status IN ('UPCOMING', 'LIVE', 'COMPLETED', 'ABANDONED')),
    CHECK (home_team_id <> away_team_id)
);

CREATE TABLE player_match_stats (
    match_id bigint REFERENCES matches (match_id) ON DELETE RESTRICT,
    player_id bigint REFERENCES players (player_id) ON DELETE RESTRICT,
    runs smallint NOT NULL CHECK (runs >= 0),
    balls_faced smallint NOT NULL CHECK (balls_faced >= 0),
    fours smallint NOT NULL CHECK (fours >= 0),
    sixes smallint NOT NULL CHECK (sixes >= 0),
    wickets smallint NOT NULL CHECK (wickets BETWEEN 0 AND 10),
    catches smallint NOT NULL CHECK (catches >= 0),
    fantasy_points numeric(9, 2) NOT NULL,
    PRIMARY KEY (match_id, player_id)
);

CREATE TABLE users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE CHECK (username ~ '^[A-Za-z0-9_]+$'),
    phone text NOT NULL UNIQUE CHECK (phone ~ '^[0-9]{10}$'),
    email text UNIQUE,
    state_code text NOT NULL CHECK (state_code ~ '^[A-Z]{2}$'),
    kyc_status text NOT NULL CHECK (kyc_status IN ('PENDING', 'REJECTED', 'VERIFIED')),
    created_at timestamptz NOT NULL
);

CREATE TABLE user_teams (
    user_team_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    match_id bigint NOT NULL REFERENCES matches (match_id) ON DELETE RESTRICT,
    team_label text NOT NULL CHECK (team_label ~ '^T[1-9][0-9]*$'),
    captain_id bigint NOT NULL REFERENCES players (player_id) ON DELETE RESTRICT,
    vice_captain_id bigint NOT NULL REFERENCES players (player_id) ON DELETE RESTRICT,
    total_points numeric(10, 2),
    created_at timestamptz NOT NULL,
    UNIQUE (user_id, match_id, team_label),
    CHECK (captain_id <> vice_captain_id)
);

CREATE TABLE user_team_players (
    user_team_id bigint REFERENCES user_teams (user_team_id) ON DELETE CASCADE,
    player_id bigint REFERENCES players (player_id) ON DELETE RESTRICT,
    PRIMARY KEY (user_team_id, player_id)
);

CREATE TABLE contests (
    contest_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id bigint NOT NULL REFERENCES matches (match_id) ON DELETE RESTRICT,
    contest_name text NOT NULL,
    contest_type text NOT NULL CHECK (contest_type IN ('HEAD_TO_HEAD', 'MEGA', 'PRIVATE', 'SMALL')),
    entry_fee numeric(14, 2) NOT NULL CHECK (entry_fee >= 0 AND entry_fee <> 'NaN'::numeric),
    total_spots integer NOT NULL CHECK (total_spots > 0),
    prize_pool numeric(14, 2) NOT NULL CHECK (prize_pool >= 0 AND prize_pool <> 'NaN'::numeric),
    is_guaranteed boolean NOT NULL,
    invite_code text UNIQUE CHECK (invite_code ~ '^[A-Z0-9]+$'),
    CHECK (contest_type <> 'HEAD_TO_HEAD' OR total_spots = 2),
    CHECK ((contest_type = 'PRIVATE') = (invite_code IS NOT NULL))
);

CREATE TABLE contest_entries (
    entry_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id bigint NOT NULL REFERENCES contests (contest_id) ON DELETE RESTRICT,
    user_team_id bigint NOT NULL REFERENCES user_teams (user_team_id) ON DELETE RESTRICT,
    joined_at timestamptz NOT NULL,
    final_rank integer CHECK (final_rank > 0),
    winnings numeric(14, 2) NOT NULL DEFAULT 0 CHECK (winnings >= 0 AND winnings <> 'NaN'::numeric),
    UNIQUE (contest_id, user_team_id)
);

CREATE TABLE wallet_transactions (
    txn_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    txn_type text NOT NULL CHECK (txn_type IN ('BONUS', 'DEPOSIT', 'ENTRY_FEE', 'REFUND', 'WINNINGS', 'WITHDRAWAL')),
    amount numeric(14, 2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    reference_entry_id bigint REFERENCES contest_entries (entry_id) ON DELETE RESTRICT,
    status text NOT NULL CHECK (status IN ('FAILED', 'PENDING', 'SUCCESS')),
    created_at timestamptz NOT NULL,
    CHECK ((txn_type IN ('ENTRY_FEE', 'REFUND', 'WINNINGS')) = (reference_entry_id IS NOT NULL))
);

COMMIT;
